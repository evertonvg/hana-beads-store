/**
 * Regenerates the product inserts of supabase/seed.sql from lib/data/mock/fixtures.ts.
 * Run: node --experimental-strip-types scripts/fixtures-to-seed.ts
 * Ids are UUID v5 of the slug (tests/contract/fixture-ids.ts). Prices stay null (never invented).
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

import type { Product } from "../lib/data/types";

const root = resolve(import.meta.dirname, "..");
// Dynamic imports: node needs the .ts extension, tsc's default settings reject it in static ones.
const { productFixtures } = (await import(
  pathToFileURL(resolve(root, "lib/data/mock/fixtures.ts")).href
)) as { productFixtures: readonly Product[] };
const { fixtureId } = (await import(
  pathToFileURL(resolve(root, "tests/contract/fixture-ids.ts")).href
)) as { fixtureId: (slug: string) => string };

const text = (s: string) => `'${s.replaceAll("'", "''")}'`;
const textArray = (a: readonly string[]) => `array[${a.map(text).join(", ")}]::text[]`;
const json = (v: unknown) => `${text(JSON.stringify(v))}::jsonb`;
const num = (n: number | null) => (n === null ? "null" : String(n));

const rows = productFixtures.map((p, i) =>
  [
    text(fixtureId(p.slug)),
    text(p.slug),
    text(p.name),
    text(p.description),
    num(p.priceCents),
    p.rarity === null ? "null" : text(p.rarity),
    String(p.isNew),
    String(p.stock),
    textArray(p.categories),
    text(p.categoryLabel),
    textArray(p.colors),
    json(p.images),
    p.art === null ? "null" : json(p.art),
    String(p.illustrative),
    num(p.sizeCm),
    num(p.beadCount),
    json(p.options),
    num(p.featuredRank),
    `timestamptz '2026-01-01 00:00:00+00' + interval '${i} seconds'`,
  ].join(", "),
);

const sql = `-- GENERATED by scripts/fixtures-to-seed.ts from lib/data/mock/fixtures.ts. Do not edit by hand.
-- created_at grows one second per fixture so (created_at, id) reproduces the catalog order.
insert into public.products (
  id, slug, name, description, price_cents, rarity, is_new, stock, categories, category_label,
  colors, images, art, illustrative, size_cm, bead_count, options, featured_rank, created_at
) values
${rows.map((r) => `  (${r})`).join(",\n")};
`;

// Keep the hand-written users block (everything from its marker on) across regenerations.
const seedPath = resolve(root, "supabase/seed.sql");
const marker = "-- BEGIN USERS";
const previous = existsSync(seedPath) ? readFileSync(seedPath, "utf8") : "";
const usersAt = previous.indexOf(marker);
writeFileSync(
  seedPath,
  usersAt === -1
    ? sql
    : `${sql}
${previous.slice(usersAt)}`,
);
console.warn(`seed.sql: ${rows.length} products`);
